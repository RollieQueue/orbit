#!/usr/bin/env node
'use strict'

/**
 * Renders the two files that mirror electron/ipc-contract.cjs and must never drift from it:
 *   src/vite-env.d.ts    — the block between the BEGIN/END markers (named payload types, `OrbitBridge`, `Window.orbit`);
 *                          everything outside the markers stays hand-written (GitContext, RuntimeEvent, ...).
 *   electron/preload.cjs — the whole file: the sandboxed preload cannot require the contract, so its table is inlined.
 * Output is deterministic with LF line endings. `node scripts/gen-ipc-types.cjs` writes what changed; `--check` only
 * reports drift (exit 1). tests/ipc-contract.test.cjs runs the same comparison. The preload is emitted with `// @ts-check`
 * and JSDoc types, so `tsc -p tsconfig.main.json` checks the generated file like the rest of the electron/ shell.
 */

const fs = require('node:fs')
const path = require('node:path')
const { TYPES, CALLS, EVENTS, ENTRIES } = require('../electron/ipc-contract.cjs')

const root = path.join(__dirname, '..')
const TYPES_FILE = path.join(root, 'src', 'vite-env.d.ts')
const PRELOAD_FILE = path.join(root, 'electron', 'preload.cjs')
const BEGIN = '// BEGIN generated from electron/ipc-contract.cjs by scripts/gen-ipc-types.cjs; do not edit between the markers.'
const END = '// END generated from electron/ipc-contract.cjs'
const REFERENCE = '/// <reference types="vite/client" />\n'

const normalize = (text) => String(text).replace(/\r\n/g, '\n')
const readIfExists = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '')

function signature(entry) {
  const params = entry.args.map(arg => `${arg.name}${arg.optional ? '?' : ''}: ${arg.type}`).join(', ')
  return `${entry.method}: (${params}) => ${entry.push ? entry.returns : `Promise<${entry.returns}>`}`
}

/** The generated block of vite-env.d.ts. */
function renderBridgeBlock() {
  const lines = [BEGIN]
  for (const [name, type] of Object.entries(TYPES)) lines.push(`type ${name} = ${type}`)
  lines.push("// The preload bridge (electron/preload.cjs) to Orbit's main process; absent when the renderer runs in a plain browser.")
  lines.push('interface OrbitBridge {')
  for (const entry of ENTRIES) lines.push(`  ${signature(entry)}`)
  lines.push('}')
  lines.push('interface Window { orbit?: OrbitBridge }')
  lines.push(END)
  return lines.join('\n') + '\n'
}

/** vite-env.d.ts with its generated block replaced (or inserted after the vite reference when the file has no markers). */
function renderTypes(current = readIfExists(TYPES_FILE)) {
  const source = normalize(current)
  const block = renderBridgeBlock()
  const begin = source.indexOf(BEGIN)
  const end = source.indexOf(END, begin)
  if (begin >= 0 && end > begin) return source.slice(0, begin) + block + source.slice(end + END.length).replace(/^\n/, '')
  return REFERENCE + block + (source.startsWith(REFERENCE) ? source.slice(REFERENCE.length) : source)
}

/** The whole preload: the contract table as data plus the two loops that build window.orbit from it. */
function renderPreload() {
  const quote = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  const lines = [
    '// @ts-check',
    '// GENERATED by scripts/gen-ipc-types.cjs from electron/ipc-contract.cjs; do not edit by hand.',
    "// The preload runs in Electron's renderer sandbox, whose require() only loads Electron's own modules, so the contract",
    '// table is inlined here instead of required. tests/ipc-contract.test.cjs fails when this file drifts from the contract.',
    "const { contextBridge, ipcRenderer } = require('electron')",
    '',
    '// [method, channel, arity]: a call forwards at most `arity` arguments (an extra one, such as the DOM event an onClick',
    '// passes, would fail structured cloning). A subscription forwards the payload and returns its unsubscribe function.',
    '/** @type {[method: string, channel: string, arity: number][]} */',
    'const CALLS = [',
    ...CALLS.map(entry => `  [${quote(entry.method)}, ${quote(entry.channel)}, ${entry.args.length}],`),
    ']',
    '/** @type {[method: string, channel: string][]} */',
    'const EVENTS = [',
    ...EVENTS.map(entry => `  [${quote(entry.method)}, ${quote(entry.channel)}],`),
    ']',
    '',
    '/** @type {Record<string, (...params: any[]) => unknown>} */',
    'const orbit = {}',
    'for (const [method, channel, arity] of CALLS) orbit[method] = (...params) => ipcRenderer.invoke(channel, ...params.slice(0, arity))',
    'for (const [method, channel] of EVENTS) {',
    '  orbit[method] = (handler) => {',
    "    /** @type {(event: import('electron').IpcRendererEvent, payload: unknown) => void} */",
    '    const listener = (_event, payload) => handler(payload)',
    '    ipcRenderer.on(channel, listener)',
    '    return () => ipcRenderer.removeListener(channel, listener)',
    '  }',
    '}',
    "contextBridge.exposeInMainWorld('orbit', orbit)",
  ]
  return lines.join('\n') + '\n'
}

/** Both targets with whether their current text differs from the rendered one; `write` stores the rendered text where it does. */
function generate({ write = false } = {}) {
  const targets = [
    { file: TYPES_FILE, render: () => renderTypes() },
    { file: PRELOAD_FILE, render: () => renderPreload() },
  ]
  return targets.map(({ file, render }) => {
    const current = normalize(readIfExists(file))
    const next = render()
    const changed = current !== next
    if (changed && write) fs.writeFileSync(file, next, 'utf8')
    return { file: path.relative(root, file).split(path.sep).join('/'), changed }
  })
}

if (require.main === module) {
  const check = process.argv.includes('--check')
  const results = generate({ write: !check })
  const drifted = results.filter(result => result.changed)
  if (check) {
    if (drifted.length) {
      console.error(`out of date with electron/ipc-contract.cjs: ${drifted.map(result => result.file).join(', ')} (run: node scripts/gen-ipc-types.cjs)`)
      process.exit(1)
    }
    console.log('src/vite-env.d.ts and electron/preload.cjs match electron/ipc-contract.cjs')
  } else {
    for (const result of results) console.log(`${result.changed ? 'wrote' : 'unchanged'} ${result.file}`)
  }
}

module.exports = { BEGIN, END, TYPES_FILE, PRELOAD_FILE, normalize, signature, renderBridgeBlock, renderTypes, renderPreload, generate }
